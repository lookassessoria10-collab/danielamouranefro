import type { NextConfig } from "next";

/*
 * Cache Components fica desligado de propósito: o site é 100% estático e, com ele
 * ligado, rotas antigas ficam "escondidas" em vez de desmontadas — o player do
 * Google Drive poderia continuar tocando o áudio depois que a pessoa sai da página.
 */
const nextConfig: NextConfig = {
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  images: {
    formats: ["image/avif", "image/webp"],
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
